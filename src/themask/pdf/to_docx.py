"""PDF to Word: the text of a PDF in a fresh Word file, to be masked like any other.

``pdf_to_docx`` reads the blocks of the PDF (``extractor.extract_blocks``) and writes them into a
new python-docx document: a heading in "Heading 1" when it is set in 14 pt or more and in
"Heading 2" otherwise, a paragraph as a plain paragraph, and a table as a ruled table whose first
row is bold. Where a page of the PDF has nothing to read, a paragraph says so: "[page 2 is an
image — not included]". Nothing comes from the PDF but its text, and the properties a new
python-docx document has of its own ("python-docx" as the author, "generated by python-docx",
its template's dates and revision) are removed.
"""

from __future__ import annotations

from pathlib import Path

import docx
from docx.document import Document

from themask.pdf.extractor import Block, PdfReport, extract_blocks

IMAGE_PAGE_NOTE = "[page {page} is an image \N{EM DASH} not included]"

_HEADING_1_SIZE = 14.0  # points: a heading this large is a "Heading 1", a smaller one "Heading 2"
_TABLE_STYLE = "Table Grid"


def pdf_to_docx(pdf: Path, out: Path) -> PdfReport:
    """Write the text of ``pdf`` into a new Word file at ``out``; returns what was left out.

    Raises ScannedPdfError when the PDF has no text to read, ProtectedFileError when it asks for
    a password and UnsupportedFileError when it cannot be read, or its layers cannot.
    """
    blocks, report = extract_blocks(pdf)
    document = docx.Document()
    properties = document.core_properties._element  # python-docx has no way to remove them
    for prop in list(properties):
        properties.remove(prop)
    running = len(report.repeated_lines_removed)  # the first blocks: each running line, once
    for block in blocks[:running]:
        _write(document, block)
    notes = sorted(report.image_only_pages)
    for block in blocks[running:]:
        while notes and notes[0] < block.page:
            document.add_paragraph(IMAGE_PAGE_NOTE.format(page=notes.pop(0)))
        _write(document, block)
    for page in notes:
        document.add_paragraph(IMAGE_PAGE_NOTE.format(page=page))
    document.save(str(out))
    return report


def _write(document: Document, block: Block) -> None:
    if block.kind == "heading":
        document.add_heading(block.text, level=1 if block.size >= _HEADING_1_SIZE else 2)
    elif block.kind == "paragraph":
        document.add_paragraph(block.text)
    else:
        rows = block.rows or []
        table = document.add_table(rows=len(rows), cols=max(map(len, rows), default=0))
        table.style = _TABLE_STYLE
        for number, (row, texts) in enumerate(zip(table.rows, rows, strict=True)):
            for cell, text in zip(row.cells, texts, strict=False):  # a short row: blank cells
                if text:
                    run = cell.paragraphs[0].add_run(text)
                    if number == 0:
                        run.bold = True
