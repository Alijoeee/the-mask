"""tools/check_bundle_lock.py: The MASK.app holds the packages uv.lock locks, at the locked versions.

Briefcase installs the app's packages with pip, which takes the newest version of every package
that nothing pins: the first build had certifi and filelock newer than uv.lock, the versions every
test ran on. packaging/build_mac.sh now hands pip the locked versions, and this check is the proof
that pip took them. Small made-up bundles cover each kind of difference; the real ``uv export`` of
this repository covers the reading of the real lock.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import tomllib
from pathlib import Path

import pytest
from packaging.utils import canonicalize_name, parse_wheel_filename
from packaging.version import Version

from tools.check_bundle_lock import (
    EXPORT_ARGUMENTS,
    bundled_packages,
    differences,
    locked_packages,
    main,
)

ROOT = Path(__file__).resolve().parent.parent

# The markers of the export below, as they come out on a Mac.
MAC = {
    "sys_platform": "darwin",
    "platform_system": "Darwin",
    "platform_python_implementation": "CPython",
}

EXPORT = """\
# This file was autogenerated by uv via the following command:
#    uv export --locked --no-dev --no-hashes
annotated-types==0.8.0
certifi==2026.7.22
cffi==2.1.1 ; platform_python_implementation != 'PyPy'
colorama==0.4.6 ; sys_platform == 'win32'
en-core-web-md @ https://github.com/explosion/spacy-models/releases/download/en_core_web_md-3.8.0/en_core_web_md-3.8.0-py3-none-any.whl
jeepney==0.9.0 ; sys_platform == 'linux'
"""


def make_packages(folder: Path, packages: dict[str, str]) -> Path:
    """An app_packages folder holding a dist-info for each ``name: version`` (and one plain package)."""
    for name, number in packages.items():
        info = folder / f"{name.replace('-', '_')}-{number}.dist-info"
        info.mkdir(parents=True)
        metadata = f"Metadata-Version: 2.1\nName: {name}\nVersion: {number}\n"
        (info / "METADATA").write_text(metadata, encoding="utf-8")
    (folder / "PySide6").mkdir()  # a package folder that is not a dist-info is no package
    return folder


def make_app(root: Path, packages: dict[str, str]) -> Path:
    """The layout of The MASK.app, with ``packages`` installed in it."""
    app = root / "The MASK.app"
    make_packages(app / "Contents" / "Resources" / "app_packages", packages)
    return app


def test_the_locked_packages_are_those_that_apply_to_this_mac() -> None:
    assert locked_packages(EXPORT, MAC) == {
        "annotated-types": Version("0.8.0"),
        "certifi": Version("2026.7.22"),
        "cffi": Version("2.1.1"),
        "en-core-web-md": Version("3.8.0"),  # locked by its URL: the version is the wheel's
    }


def test_a_line_that_is_not_a_requirement_is_refused() -> None:
    with pytest.raises(ValueError, match="cannot read"):
        locked_packages("certifi>=2026.7.22\n", MAC)


def test_the_bundled_packages_are_read_from_their_dist_infos(tmp_path: Path) -> None:
    folder = make_packages(
        tmp_path / "app_packages", {"Annotated_Types": "0.8.0", "certifi": "1.0"}
    )
    assert bundled_packages(folder) == {
        "annotated-types": Version("0.8.0"),
        "certifi": Version("1.0"),
    }


def test_every_kind_of_difference_is_named() -> None:
    bundle = {
        "certifi": Version("2026.10.18"),
        "extra-package": Version("1.0"),
        "cffi": Version("2.1.1"),
    }
    locked = {
        "certifi": Version("2026.7.22"),
        "cffi": Version("2.1.1"),
        "annotated-types": Version("0.8.0"),
    }
    assert differences(bundle, locked) == [
        "annotated-types 0.8.0 is locked for this Mac, but is not in the app",
        "certifi is 2026.10.18 in the app, 2026.7.22 in uv.lock",
        "extra-package 1.0 is in the app, but uv.lock does not lock it for this Mac",
    ]


def test_versions_are_compared_as_versions_not_as_spellings() -> None:
    assert differences({"certifi": Version("2026.07.22")}, {"certifi": Version("2026.7.22")}) == []


def test_a_package_locked_without_a_version_only_has_to_be_there() -> None:
    assert differences({"model": Version("3.8.0")}, {"model": None}) == []
    assert differences({}, {"model": None}) == [
        "model is locked for this Mac, but is not in the app"
    ]


# ---- the real lock -------------------------------------------------------------------------------


@pytest.fixture(scope="module")
def real_export() -> str:
    """What ``uv export`` says of this repository's uv.lock."""
    uv = shutil.which("uv")
    if uv is None:
        pytest.skip("uv is not on the PATH")
    done = subprocess.run(
        [uv, *EXPORT_ARGUMENTS], cwd=ROOT, capture_output=True, text=True, timeout=120, check=False
    )
    assert done.returncode == 0, done.stderr
    return done.stdout


def test_the_real_lock_holds_every_pinned_runtime_dependency_at_its_pin(real_export: str) -> None:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    locked = locked_packages(real_export)
    for requirement in project["dependencies"]:
        name, _, pin = requirement.partition("==")
        if pin:
            assert locked[canonicalize_name(name)] == Version(pin), requirement
        else:  # the language model, pinned by the URL of its wheel
            name, _, url = requirement.partition(" @ ")
            wheel = parse_wheel_filename(url.rsplit("/", 1)[-1])
            assert locked[canonicalize_name(name)] == wheel[1], requirement


def test_main_says_ok_for_a_bundle_that_is_the_lock(
    real_export: str, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    locked = locked_packages(real_export)
    app = make_app(tmp_path, {name: str(version) for name, version in locked.items() if version})
    assert main([str(app)]) == 0
    assert re.search(
        r"The app's \d+ packages are the \d+ that uv.lock locks", capsys.readouterr().out
    )


def test_main_fails_and_says_what_differs(
    real_export: str, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    locked = locked_packages(real_export)
    packages = {name: str(version) for name, version in locked.items() if version}
    packages["certifi"] = "1999.1.1"
    del packages["numpy"]
    packages["not-in-the-lock"] = "1.0"
    assert main([str(make_app(tmp_path, packages))]) == 1
    printed = capsys.readouterr().out
    assert "certifi is 1999.1.1 in the app, " in printed
    assert "numpy " in printed and "is locked for this Mac, but is not in the app" in printed
    assert "not-in-the-lock 1.0 is in the app, but uv.lock does not lock it" in printed


def test_main_asks_for_the_app_to_be_built_first(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    assert main([str(tmp_path / "The MASK.app")]) == 2
    assert "build the app first" in capsys.readouterr().err
